const normalize = (value: string) =>
  value
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");

const section = (
  id: string,
  type: string,
  title: string,
  subtitle: string,
  content: string,
  ctaLabel: string,
  items: string[],
  layout: string,
  conversionRole: string,
): SiteSection => ({
  id,
  type,
  title,
  subtitle,
  content,
  cta: { label: ctaLabel, action: type === "contact" || type === "cta" ? "#contact" : `#${id}` },
  items,
  media: [],
  layout,
  conversionRole,
});

const cityText = (city: string) => (city && normalize(city) !== "france" ? ` a ${city}` : "");

const ctaForGoal = (goal: string, fallback: string) => {
  const normalized = normalize(goal);
  if (/(reservation|reserver|rendez-vous|rdv|booking)/.test(normalized)) return "Reserver un rendez-vous";
  if (/(devis|lead|demande|contact)/.test(normalized)) return "Demander un devis";
  if (/(vendre|vente|achat|acheter|checkout|commande)/.test(normalized)) return "Acheter maintenant";
  if (/(appel|audit|diagnostic)/.test(normalized)) return "Planifier un audit";
  return fallback;
};

