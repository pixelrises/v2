export const resolveSiteBlueprint = (input: SiteBlueprintInput): SiteBlueprint => {
  const haystack = normalize(
    [input.businessName, input.niche, input.city, input.goal, input.offer, input.targetAudience, input.style]
      .filter(Boolean)
      .join(" "),
  );
  return blueprints.find((blueprint) => blueprint.match.test(haystack)) ?? blueprints[blueprints.length - 1];
};

export const createNicheSiteProjectParts = (input: SiteBlueprintInput) => {
  const blueprint = resolveSiteBlueprint(input);
  const cta = ctaForGoal(input.goal, blueprint.primaryCTA);
  const sections = blueprint.sections(input).map((item) => ({
    ...item,
    cta: { ...item.cta, label: item.type === "hero" || item.type === "cta" || item.type === "contact" ? cta : item.cta.label },
  }));

  return {
    blueprint,
    cta,
    sections,
    strategy: {
      mainPromise: blueprint.mainPromise(input),
      marketingAngle: blueprint.marketingAngle(input),
      trustStrategy: `${blueprint.trustElements.join(", ")} places pres des decisions importantes.`,
      objectionsToHandle: blueprint.objections,
    },
    brand: {
      tagline: blueprint.tagline(input),
      tone: `${blueprint.visualMood}, direct, concret`,
    },
    business: {
      valueProposition: blueprint.valueProposition(input),
      pricingSuggestion: blueprint.pricingSuggestion,
      leadCapture: blueprint.leadCapture,
      trustElements: blueprint.trustElements,
    },
    conversion: {
      ctaStrategy: `CTA principal "${cta}" dans le hero, rappel apres les preuves et CTA final contextualise.`,
      objections: blueprint.objections,
      proofElements: blueprint.trustElements,
      recommendedSections: blueprint.recommendedSections,
    },
    design: {
      layoutDirection: blueprint.layoutDirection,
      visualMood: blueprint.visualMood,
      components: blueprint.components,
    },
  };
};

